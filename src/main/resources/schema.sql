CREATE TABLE IF NOT EXISTS app_lock (id INT PRIMARY KEY);
MERGE INTO app_lock KEY(id) VALUES (1);
CREATE TABLE IF NOT EXISTS restaurant_settings (
 id INT PRIMARY KEY, deposit_per_table BIGINT NOT NULL, hold_minutes INT NOT NULL,
 cleanup_minutes INT NOT NULL, open_hour INT NOT NULL, close_hour INT NOT NULL, grace_minutes INT NOT NULL
);
CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(180) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 full_name VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL, role VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS dining_table (
 id BIGINT PRIMARY KEY, code VARCHAR(10) NOT NULL UNIQUE, zone VARCHAR(60) NOT NULL,
 map_x INT NOT NULL, map_y INT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS retired BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE dining_table ADD COLUMN IF NOT EXISTS floor INT NOT NULL DEFAULT 1;
CREATE TABLE IF NOT EXISTS app_migration (name VARCHAR(80) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS table_combination (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, table_ids VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS menu_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL,
 description VARCHAR(400) NOT NULL, category VARCHAR(50) NOT NULL,
 price BIGINT NOT NULL, available BOOLEAN NOT NULL, illustration VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS reservation (
 id VARCHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 start_at TIMESTAMP NOT NULL, end_at TIMESTAMP NOT NULL, guests INT NOT NULL,
 notes VARCHAR(500) NOT NULL, status VARCHAR(30) NOT NULL, payment_status VARCHAR(30) NOT NULL,
 deposit BIGINT NOT NULL, created_at TIMESTAMP NOT NULL, hold_until TIMESTAMP NOT NULL,
 paid_at TIMESTAMP, payment_provider VARCHAR(20), payment_reference VARCHAR(100), refund_reference VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS reservation_schedule ON reservation(start_at, end_at, status);
ALTER TABLE reservation ADD COLUMN IF NOT EXISTS released_at TIMESTAMP;
CREATE TABLE IF NOT EXISTS reservation_table (
 reservation_id VARCHAR(36) NOT NULL REFERENCES reservation(id), table_id BIGINT NOT NULL REFERENCES dining_table(id),
 PRIMARY KEY(reservation_id, table_id)
);
CREATE TABLE IF NOT EXISTS order_line (
 reservation_id VARCHAR(36) NOT NULL REFERENCES reservation(id), menu_item_id BIGINT NOT NULL REFERENCES menu_item(id),
 item_name VARCHAR(100) NOT NULL, unit_price BIGINT NOT NULL, quantity INT NOT NULL,
 PRIMARY KEY(reservation_id, menu_item_id)
);
CREATE TABLE IF NOT EXISTS change_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reservation_id VARCHAR(36) NOT NULL REFERENCES reservation(id),
 message VARCHAR(500) NOT NULL, created_at TIMESTAMP NOT NULL, status VARCHAR(20) NOT NULL,
 response VARCHAR(500) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS audit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reservation_id VARCHAR(36) NOT NULL REFERENCES reservation(id),
 actor VARCHAR(180) NOT NULL, action VARCHAR(100) NOT NULL, created_at TIMESTAMP NOT NULL
);
